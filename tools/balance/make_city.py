"""Build the city description the balance tool reads (city.json) from Big Copilot's data.

    python3 tools/balance/make_city.py [--big-copilot ~/big-copilot] [--save SAVE.hsg] [--out tools/balance/city.json]

Inputs, all read-only:
- ba_buildings.json: the 885 buildings with street, number, neighbourhood, type and traffic.
- web/maps/locations.json: each address's outline on Big Copilot's city map, in map units.
- --save (optional): business types from a save's building registrations. Only businesses the
  player doesn't rent are kept: the fixed AI ones every game has (wholesalers, gas stations,
  banks...) and the rivals of that game. Without --save, FIXED_BUSINESSES below is used.

The game's door positions are in no file, so positions are approximated (see SCALE): each
building is its map outline's bounding box, converted to metres per map region.
"""
import argparse
import json
import os

SCALE = {"mainland": 1.0, "industry-city": 1.49, "the-hamptons": 3.2}

FIXED_BUSINESSES = {
    "ba:street_firststreet#37": "ba:businesstype_wholesalestore",
    "ba:street_firststreet#18": "ba:businesstype_wholesalestore",
    "ba:street_sixthavenue#4": "ba:businesstype_wholesalestore",
    "ba:street_sixthstreet#1": "ba:businesstype_wholesalestore",
    "ba:street_twelfthstreet#13": "ba:businesstype_wholesalestore",
    "ba:street_twentyfifthstreet#4": "ba:businesstype_wholesalestore",
}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--big-copilot", default=os.path.expanduser("~/big-copilot"))
    p.add_argument("--save")
    p.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "city.json"))
    a = p.parse_args()

    with open(os.path.join(a.big_copilot, "ba_buildings.json"), encoding="utf-8") as fh:
        facts = {f"{b['s']}#{b['n']}": b for b in json.load(fh)}
    with open(os.path.join(a.big_copilot, "web", "maps", "locations.json"), encoding="utf-8") as fh:
        shapes = {b["key"]: b for b in json.load(fh)["buildings"]}

    businesses = dict(FIXED_BUSINESSES)
    source = "fixed AI businesses only"
    if a.save:
        import sys
        sys.path.insert(0, a.big_copilot)
        from ba_save import load_save  # noqa: E402
        regs = load_save(a.save).root["BuildingRegistrations"]["$items"]
        businesses = {}
        for r in regs:
            t = r.get("businessTypeName")
            if not t or t == "ba:businesstype_empty" or r.get("RentedByPlayer"):
                continue
            businesses[f"{r['StreetName']}#{r['StreetNumber']}"] = t
        source = "fixed AI and rival businesses from one save (rivals differ per game)"

    buildings = []
    for key, f in sorted(facts.items()):
        shape = shapes.get(key)
        if not shape or not shape.get("bounds"):
            continue
        s = SCALE[shape["region"]]
        x, y, w, h = shape["bounds"]
        ax, ay = shape["anchor"]
        buildings.append({
            "key": key, "region": shape["region"], "hood": "ba:neighborhood_" + f["h"],
            "buildingType": "ba:buildingtype_" + f["t"], "businessType": businesses.get(key),
            "size": f["z"], "m2": f["m"], "traffic": f["x"],
            "x": round(ax * s, 1), "z": round(ay * s, 1),
            "box": [round(x * s, 1), round(y * s, 1), round((x + w) * s, 1), round((y + h) * s, 1)],
        })

    out = {"_notes": "Generated by tools/balance/make_city.py from Big Copilot's ba_buildings.json and map outlines. "
                     "Positions in metres, approximated per map region (see SCALE there). Business types: " + source + ".",
           "scale": SCALE, "buildings": buildings}
    with open(a.out, "w", encoding="utf-8") as fh:
        json.dump(out, fh, separators=(",", ":"))
    print(f"wrote {a.out}: {len(buildings)} buildings, {sum(1 for b in buildings if b['businessType'])} with a business type")


if __name__ == "__main__":
    main()
